const CJK = /[\u3400-\u9fff\uf900-\ufaff]/;

interface Compiled {
  templates: Template[];
  keys: string[];
  terms: Record<string, string>;
}
const compiled = new Map<string, Compiled>();

function compile(gameId: string): Compiled {
  let c = compiled.get(gameId);
  if (!c) {
    const g = G[gameId] ?? { terms: {} };
    const terms = { ...COMMON, ...g.terms };
    c = {
      templates: g.templates ?? [],
      keys: Object.keys(terms).sort((a, b) => b.length - a.length),
      terms,
    };
    compiled.set(gameId, c);
  }
  return c;
}

function glossary(c: Compiled, text: string): string {
  let out = '';
  let i = 0;
  outer: while (i < text.length) {
    for (const k of c.keys) {
      if (k && text.startsWith(k, i)) {
        out += ` ${c.terms[k]} `;
        i += k.length;
        continue outer;
      }
    }
    out += text[i];
    i += 1;
  }
  return out
    .replace(/\s+/g, ' ')
    .replace(/\s+([,):])/g, '$1')
    .replace(/\(\s+/g, '(')
    .trim();
}

const ABORT_EN = 'Abort this run and settle honestly';

/** Translate one short engine string for `target` language (defaults to UI language). */
export function term(gameId: string, text: string, target: Lang = lang()): string {
  if (!text) return text;
  if (text === ABORT_EN) return target === 'zh' ? '放弃本局' : 'Abort run';
  if (target === 'zh' || !CJK.test(text)) return text;
  const c = compile(gameId);
  for (const [re, tpl] of c.templates) {
    const m = re.exec(text);
    if (!m) continue;
    const arg = m[1] ?? '';
    const out = tpl
      .replace('$P', PLOTS[arg] ?? arg)
      .replace('$T', glossary(c, arg))
      .replace('$1', arg);
    if (!CJK.test(out)) return out;
  }
  const out = glossary(c, text);
  return CJK.test(out) ? text : out;
}

/** True when `text` can be shown in English without falling back. */
export function translatable(gameId: string, text: string): boolean {
  return !CJK.test(term(gameId, text, 'en'));
}
